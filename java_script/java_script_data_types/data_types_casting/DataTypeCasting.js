console.log(numberOne*numberTwo,typeof (numberOne*numberTwo))
console.log(numberOne/numberTwo,typeof (numberOne/numberTwo))
console.log(numberOne%numberTwo,typeof (numberOne%numberTwo))
console.log(numberOne==numberTwo,typeof (numberOne==numberTwo))
   
